const dictionaries = { en, vi, zh } as const;
export type Locale = keyof typeof dictionaries;

export function localeOf(lang: string): Locale {
  const code = lang.toLowerCase().slice(0, 2);
  return code === 'vi' || code === 'zh' ? code : 'en';
}

export function format(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

/** The UI strings of the page language, and the path prefix of that locale. */
export function useStrings() {
  const { lang } = useData();
  const locale = computed(() => localeOf(lang.value));
  const strings = computed(() => dictionaries[locale.value]);
  const t = (key: keyof Strings, values?: Record<string, string | number>) => format(strings.value[key], values);
  const prefix = computed(() => (locale.value === 'en' ? '' : `${locale.value}/`));
  return { t, locale, prefix };
}
